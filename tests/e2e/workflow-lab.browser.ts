import {test,expect,type Page} from '@playwright/test';
async function predict(page:Page,state:string,blocked:string){await page.getByRole('combobox',{name:'Final state',exact:true}).selectOption({label:state});await page.getByLabel('Blocked events',{exact:true}).fill(blocked);await page.getByRole('button',{name:'Check prediction',exact:true}).click();await expect(page.getByRole('region',{name:'Computed workflow result'})).toBeVisible();}
async function changeReadyEdit(page:Page,to='In review'){
 await page.getByText('Change Edit from Ready',{exact:true}).click();
 await page.getByLabel('Edit from Ready destination',{exact:true}).selectOption({label:to});
 await page.getByLabel('Edit from Ready reason',{exact:true}).fill('Explore how an edited document returns to review.');
 await page.getByText('Change Edit from Ready',{exact:true}).locator('../..').getByRole('button',{name:'Apply rule',exact:true}).click();
 await expect(page.getByRole('combobox',{name:'Final state',exact:true})).toBeVisible();
}
test('actual edit, computed correction, separate transfer and restart preserve the first attempt',async({page})=>{
 await page.goto('/workflow-demo.html');
 await expect(page.getByText('Illustrative local sample · Document review sample')).toBeVisible();
 await expect(page.getByText('Unseen equipment checkout sample',{exact:true})).toHaveCount(0);
 await expect(page.getByRole('region',{name:'Computed workflow result'})).toHaveCount(0);
 await page.getByRole('button',{name:'Save current notes',exact:true}).click();
 await expect(page.getByLabel('Saved workflow notes')).not.toContainText('Available');
 await predict(page,'Ready','0');
 await expect(page.getByRole('region',{name:'Computed workflow result'})).toContainText('Prediction score: 0 / 2');
 await expect(page.getByRole('heading',{name:'Final state: Draft',exact:true})).toBeVisible();
 await changeReadyEdit(page);
 await expect(page.getByRole('region',{name:'Computed workflow result'})).toHaveCount(0);
 await page.getByRole('button',{name:'Deep',exact:true}).click();
 await predict(page,'Ready','0');
 await expect(page.getByLabel('Computed workflow change')).toContainText('Blocked events: 1 → 0');
 await expect(page.getByLabel('Computed workflow change')).toContainText('Final state: Draft → Ready');
 await page.getByRole('button',{name:'Visual',exact:true}).click();
 await expect(page.getByRole('button',{name:'Visual',exact:true})).toHaveCSS('background-color','rgb(32, 32, 32)');
 await expect(page.getByLabel('Computed state path')).toBeVisible();
 await page.screenshot({path:'evidence/workflow-lab/changed-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Try unseen transfer',exact:true}).click();
 await expect(page.getByText('Unseen synthetic transfer · Unseen equipment checkout sample')).toBeVisible();
 await expect(page.getByRole('region',{name:'Computed workflow result'})).toHaveCount(0);
 await expect(page.getByText('Change Edit from Ready',{exact:true})).toHaveCount(0);
 await predict(page,'Reserved','1');
 await expect(page.getByRole('region',{name:'Computed workflow result'})).toContainText('First transfer prediction score: 0 / 2');
 await expect(page.getByRole('heading',{name:'Final state: Available',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Return to practice',exact:true}).click();
 await changeReadyEdit(page,'Draft');
 await page.getByRole('button',{name:'Reload local store',exact:true}).click();
 await expect(page.getByRole('combobox',{name:'Final state',exact:true})).toBeVisible();
 await predict(page,'Draft','1');
 await page.getByRole('button',{name:'Open saved transfer',exact:true}).click();
 await expect(page.getByRole('region',{name:'Computed workflow result'})).toContainText('First transfer prediction score: 0 / 2');
 await expect(page.getByRole('combobox',{name:'Final state',exact:true})).toHaveCount(0);
 await page.reload();
 await expect(page.getByRole('heading',{name:'Final state: Available',exact:true})).toBeVisible();
 await page.screenshot({path:'evidence/workflow-lab/transfer-desktop.png',fullPage:true});
});
test('source-reviewed rule provenance stays visible after a local edit and stale source blocks further writes',async({page})=>{
 await page.goto('/workflow-demo.html?source=true');
 await expect(page.getByText('Reviewed source interpretation · Document review sample')).toBeVisible();
 await changeReadyEdit(page);
 await predict(page,'Ready','0');
 await page.getByText('Original rule interpretations, source and changes',{exact:true}).click();
 await expect(page.getByText('Ready + Edit -> Draft',{exact:true})).toBeVisible();
 await expect(page.getByText('Explore how an edited document returns to review.',{exact:false}).first()).toBeVisible();
 await page.getByRole('button',{name:'Save current notes',exact:true}).click();
 await expect(page.getByLabel('Saved workflow notes')).toContainText('Ready + Edit -> Draft');
 await expect(page.getByLabel('Saved workflow notes')).not.toContainText('Available');
 await page.screenshot({path:'evidence/workflow-lab/reviewed-source.png',fullPage:true});
 await page.getByRole('button',{name:'Change synthetic source',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('reviewed source changed');
 await expect(page.getByRole('button',{name:'Visual',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'Reload local store',exact:true}).click();
 await expect(page.getByRole('button',{name:'Deep',exact:true})).toBeDisabled();
 await page.screenshot({path:'evidence/workflow-lab/stale-source.png',fullPage:true});
});
