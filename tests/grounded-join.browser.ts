import {expect,test} from '@playwright/test';
test('cited source correction feeds the working join, persists mode/results and blocks stale source replay',async({page,request})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/grounded-join-demo.html');
 await expect(page.getByRole('heading',{name:'Work with the cited table data'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Accept reviewed extraction and experiment'})).toBeDisabled();
 await page.screenshot({path:'evidence/grounded-join/blocked-review-desktop.png',fullPage:true});
 await page.setViewportSize({width:360,height:900});await page.screenshot({path:'evidence/grounded-join/blocked-review-360.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.setViewportSize({width:1280,height:800});
 const value=page.getByLabel('Members row 2, Team corrected value',{exact:true});
 await value.fill('x');await page.getByLabel('Members row 2, Team correction reason',{exact:true}).fill('User supplied x for the unreadable key.');
 await page.getByRole('cell').filter({has:value}).getByRole('button',{name:'Apply correction'}).click();
 await expect(page.getByText('User-corrected source data',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Accept reviewed extraction and experiment'}).click();
 await page.getByLabel('Predict the output row count').fill('4');await page.getByRole('button',{name:'Check prediction'}).click();
 await expect(page.getByRole('heading',{name:'4 output rows'})).toBeVisible();
 await page.getByRole('group',{name:'Grounded explanation style'}).getByRole('button',{name:'Visual',exact:true}).click();
 await expect(page.getByRole('list',{name:'Pair map'}).getByRole('listitem')).toHaveCount(4);
 await page.getByLabel('Join type',{exact:true}).selectOption('LEFT');
 await page.getByLabel('Predict the output row count').fill('4');await page.getByRole('button',{name:'Check prediction'}).click();
 await expect(page.getByRole('heading',{name:'5 output rows'})).toBeVisible();
 await expect(page.getByLabel('Computed change summary')).toContainText('4 → 5 rows');
 await page.screenshot({path:'evidence/grounded-join/corrected-change-desktop.png',fullPage:true});
 await page.reload();
 await expect(page.getByRole('heading',{name:'5 output rows'})).toBeVisible();
 await expect(page.getByRole('group',{name:'Grounded explanation style'}).getByRole('button',{name:'Visual',exact:true})).toHaveAttribute('aria-pressed','true');
 await page.getByRole('button',{name:'Try separate challenge'}).click();
 await expect(page.getByRole('heading',{name:'Separate synthetic challenge'})).toBeVisible();
 await page.getByLabel('Predict the output row count').fill('6');await page.getByRole('button',{name:'Check prediction'}).click();
 await expect(page.getByText('Transfer score: 1 / 1',{exact:false})).toBeVisible();
 const taskId=new URL(page.url()).searchParams.get('task');
 await page.getByRole('button',{name:'Change synthetic source'}).click();
 await expect(page.getByRole('alert')).toContainText('saved extraction is historical');
 await expect(page.getByRole('heading',{name:'6 output rows'})).toBeVisible();
 await expect(page.getByRole('group',{name:'Grounded explanation style'}).getByRole('button',{name:'Deep',exact:true})).toBeDisabled();
 const before=await (await request.get('/__grounded/state?task='+taskId)).json(),saved=before.task.session.moduleStates[0];
 const refused=await request.post('/__grounded/edit',{data:{taskId,artifactId:before.artifactId,artifactRevision:1,moduleId:'source-join',action:{kind:'explanation-mode',mode:'deep',expectedRevision:saved.state.revision}}});
 expect(refused.status()).toBe(409);
 const after=await (await request.get('/__grounded/state?task='+taskId)).json();expect(after.task.session.moduleStates).toEqual(before.task.session.moduleStates);
 await page.setViewportSize({width:360,height:900});await page.screenshot({path:'evidence/grounded-join/stale-transfer-360.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);expect(errors).toEqual([]);
});
test('reviewed observed data stays separate from corrections and a changed basis artifact retires live editing',async({page})=>{
 await page.goto('/grounded-join-demo.html?ambiguous=false');
 await expect(page.getByText('Observed source data: transcription for review',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Accept reviewed extraction and experiment'}).click();
 await page.getByLabel('Predict the output row count').fill('2');await page.getByRole('button',{name:'Check prediction'}).click();
 await expect(page.getByRole('heading',{name:'2 output rows'})).toBeVisible();
 await page.getByRole('button',{name:'Revise cited artifact'}).click();
 await expect(page.getByRole('alert')).toContainText('cited artifact changed');
 await expect(page.getByLabel('Join type',{exact:true})).toBeDisabled();
 await expect(page.getByRole('heading',{name:'2 output rows'})).toBeVisible();
 await page.screenshot({path:'evidence/grounded-join/stale-basis-desktop.png',fullPage:true});
});
for(const cited of [false,true])test(`accepted ${cited?'source-cited':'proposed'} join premise remains visible after acceptance and restore`,async({page})=>{
 await page.goto(`/grounded-join-demo.html?ambiguous=false&cited=${cited}`);
 const reason=cited?'The source explicitly specifies INNER equality on Team.':'Equality on the displayed Team columns is the proposed model.';
 const mapping=page.getByLabel('Original join mapping',{exact:true});
 await expect(mapping).toContainText(cited?'Source-cited mapping':'Proposed assumption (no source citation)');
 await expect(mapping).toContainText(reason);
 await page.getByRole('button',{name:'Accept reviewed extraction and experiment'}).click();
 await page.getByLabel('Predict the output row count').fill('2');await page.getByRole('button',{name:'Check prediction'}).click();
 await expect(page.getByRole('heading',{name:'2 output rows'})).toBeVisible();
 await expect(mapping).toContainText(reason);if(cited)await expect(mapping).toContainText('Citation');
 await page.reload();await expect(mapping).toContainText(reason);
 await page.setViewportSize(cited?{width:1280,height:900}:{width:360,height:900});
 await page.screenshot({path:`evidence/grounded-corrections/${cited?'cited-accepted-desktop':'proposed-accepted-360'}.png`,fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
